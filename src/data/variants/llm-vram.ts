export interface LlmVramVariant extends ToolVariant {
  vram: VramInput;
}

const DEFAULT_CTX = 8192;
const n = (x: number) => x.toLocaleString('en-US');

interface Facts {
  p: ModelPreset;
  ctx: number;
  q4: VramResult;
  q8: VramResult;
  fp16: VramResult;
  /** Q4_K_M at the model's maximum context. */
  max: VramResult;
  /** KV cache bytes per token, in KiB. */
  kvKiB: number;
  /** Any quant / context, same preset. */
  at: (quant: Quant, context?: number) => VramResult;
}

const g = (r: VramResult) => `${formatGiB(r.totalGiB)} GiB`;
const an = (gib: number) => (gib === 8 || gib === 80 ? 'an' : 'a');
const tier = (r: VramResult) => (r.minTierGiB ? `${an(r.minTierGiB)} ${r.minTierGiB} GiB card` : 'more than a single 80 GiB card');
const cards = (r: VramResult) => r.tiers.find((t) => t.gib === r.minTierGiB)?.cards.join(', ') ?? '';
const tierWithCards = (r: VramResult) =>
  r.minTierGiB ? `${r.minTierGiB} GiB (${cards(r)})` : 'beyond any single 80 GiB card, so it needs several GPUs or a large unified-memory machine';

function facts(p: ModelPreset): Facts {
  const ctx = Math.min(DEFAULT_CTX, p.maxContext);
  const at = (quant: Quant, context = ctx) => {
    const r = estimate({ params: p.params, quant, context, preset: p.slug });
    if (!r.valid) throw new Error(`llm-vram variant ${p.slug}: ${r.error}`);
    return r;
  };
  return {
    p,
    ctx,
    q4: at('q4_k_m'),
    q8: at('q8_0'),
    fp16: at('fp16'),
    max: at('q4_k_m', p.maxContext),
    kvKiB: (2 * p.layers * p.kvHeads * p.headDim * 2) / 1024,
    at,
  };
}

