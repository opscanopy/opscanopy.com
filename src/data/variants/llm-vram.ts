function variant(p: ModelPreset): LlmVramVariant {
  const h = HAND[p.slug];
  if (!h) throw new Error(`llm-vram variant ${p.slug}: no hand-written copy`);
  const f = facts(p);
  const vram: VramInput = { params: p.params, quant: 'q4_k_m', context: f.ctx, preset: p.slug };
  const short = h.short ?? p.name;
  const longTitle = `${short} VRAM Requirements — Q4, Q8, FP16 + KV Cache`;
  const atMax = f.ctx === p.maxContext;

  return {
    slug: p.slug,
    input: [vram.params, vram.quant, vram.context, vram.preset].join('|'),
    vram,
    h1Name: `${p.name} VRAM`,
    headline: 'what it needs at Q4_K_M, Q8_0 and FP16',
    title: longTitle.length <= 60 ? longTitle : `${short} VRAM Requirements — Q4, Q8, FP16`,
    description: `${short} needs ${g(f.q4)} at Q4_K_M, ${g(f.q8)} at Q8_0 and ${g(f.fp16)} at FP16 with an 8k context. KV cache, GPU fit and quant advice.`,
    lede: `At Q4_K_M with an ${n(f.ctx)}-token context, ${p.name} needs about ${formatGiB(estimate(vram).totalGiB)} GiB of VRAM: ${formatGiB(f.q4.weightsGiB)} GiB of weights, ${formatGiB(f.q4.kvGiB)} GiB of KV cache and ${formatGiB(f.q4.overheadGiB)} GiB of runtime overhead. The smallest common GPU tier that holds it is ${tierWithCards(f.q4)}.`,
    sections: [
      {
        heading: `How much VRAM ${p.name} needs`,
        paragraphs: [
          h.about,
          `With ${n(f.ctx)} tokens of context the estimate is ${g(f.fp16)} at FP16, ${g(f.q8)} at Q8_0 and ${g(f.q4)} at Q4_K_M. FP16 needs ${tier(f.fp16)}, Q8_0 needs ${tier(f.q8)}, and Q4_K_M needs ${tier(f.q4)}. The weights are ${p.params} billion parameters times the bits per weight of each format (${f.fp16.bpw}, ${f.q8.bpw} and ${f.q4.bpw}), divided by eight; everything is in GiB, the unit GPU memory is sold in.`,
        ],
      },
      {
        heading: 'Context length and the KV cache',
        paragraphs: [
          `The KV cache stores a key and a value vector for every token in every layer. ${p.name} has ${p.layers} layers, ${p.kvHeads} KV heads and a head dimension of ${p.headDim}, read from its Hugging Face \`config.json\`, so at FP16 each token costs ${f.kvKiB} KiB. That is ${formatGiB(f.q4.kvGiB)} GiB at ${n(f.ctx)} tokens${
            atMax
              ? `, which is also the model's maximum context.`
              : `, and ${formatGiB(f.max.kvGiB)} GiB at the maximum of ${n(p.maxContext)}, where the Q4_K_M total becomes ${g(f.max)} and needs ${tier(f.max)}.`
          } The cache does not shrink with weight quantization; only a runtime option that quantizes the cache itself does.`,
        ],
      },
      { heading: 'Which quantization to pick', paragraphs: [h.pick(f)] },
      { heading: 'Pitfalls', paragraphs: [h.pitfall(f), h.related] },
    ],
    faqs: h.faqs(f),
  };
}

export const llmVramVariants: LlmVramVariant[] = PRESETS.map(variant);
