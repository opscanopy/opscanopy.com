/**
 * cert-chain — the fixture corpus: real PEM text as named string constants.
 *
 * No binary files anywhere in the repo (nothing to git-lfs, nothing opaque in a
 * diff, and Vitest imports them with zero setup). Two provenances, both stated
 * per constant:
 *
 *   1. REAL, PUBLIC certificates fetched on 2026-07-30 — the Let's Encrypt /
 *      ISRG roots and intermediates, plus leaves captured from badssl.com with
 *      `openssl s_client`. These are the ground-truth anchors: ISRG Root X1's
 *      SHA-256 fingerprint is pinned against the value ISRG publishes, R11
 *      really is signed by X1, and E5 really is signed by X2.
 *
 *   2. GENERATED with OpenSSL 3.1.4 for cases no public certificate can supply
 *      on demand — a SHA-1 signature, an RSA-PSS signature, a v1 certificate, a
 *      multi-valued RDN, a GeneralizedTime notAfter, a subject full of HTML.
 *      These are real DER with real signatures; only the names are fictional.
 *
 * EVERY expiry assertion in the test files injects `now` explicitly, so no test
 * here can rot. The two exceptions are deliberate and load-bearing:
 * BADSSL_EXPIRED_LEAF is permanently expired (2015) and DEMO_LEAF_NOT_YET_VALID
 * is not valid until 2028 — those are the fixtures whose whole job is to be
 * outside their validity window.
 *
 * No private key material is committed. FAKE_PRIVATE_KEY_BLOCK is a
 * deliberately non-key body: the tool recognises the label and refuses to look
 * inside, so there is nothing to be gained by making it real, and a real key in
 * a public repo trips every secret scanner on earth for no benefit.
 */

