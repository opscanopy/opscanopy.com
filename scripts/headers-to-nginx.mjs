// Translate dist/_headers into an nginx config include, for the self-host image.
//
// public/_headers is Cloudflare Static Assets syntax and means nothing to nginx,
// so a container that just served dist/ would ship WITHOUT the Content-Security-
// Policy, HSTS and the rest — a materially weaker posture than production, on a
// site whose whole pitch is that your input never leaves the browser. Rather
// than hand-maintain a second copy of the policy (which would silently drift the
// first time a CSP hash changed), this derives the nginx form from the same file
// the deploy uses, AFTER postbuild has injected the real script hashes.
//
// Scope: the `/path/*` prefix rules and the global `/*` rule that _headers
// actually uses. It is not a general Cloudflare-syntax parser and does not try
// to be — it fails loudly on a shape it does not recognise rather than silently
// dropping a header.
//
//   node scripts/headers-to-nginx.mjs [--in dist/_headers] [--out dist/nginx-headers.conf]

import { readFileSync, writeFileSync } from 'node:fs';

const args = process.argv.slice(2);
const arg = (name, fallback) => {
  const i = args.indexOf(name);
  return i !== -1 && args[i + 1] ? args[i + 1] : fallback;
};

const IN = arg('--in', 'dist/_headers');
const OUT = arg('--out', 'dist/nginx-headers.conf');

const src = readFileSync(IN, 'utf8');

if (src.includes('{{SCRIPT_HASHES}}')) {
  console.error(
    `${IN} still contains the {{SCRIPT_HASHES}} marker — run the full build ` +
      '(npm run build) so scripts/inject-csp-hashes.mjs replaces it first. ' +
      'Serving the marker verbatim is invalid CSP.',
  );
  process.exit(1);
}

/** @type {{ path: string, headers: [string, string][] }[]} */
const rules = [];
let current = null;

for (const rawLine of src.split('\n')) {
  const line = rawLine.replace(/\r$/, '');
  if (!line.trim() || line.trimStart().startsWith('#')) continue;

  if (line.startsWith('/')) {
    current = { path: line.trim(), headers: [] };
    rules.push(current);
    continue;
  }

  const m = line.match(/^\s+([A-Za-z0-9-]+):\s*(.+)$/);
  if (!m) {
    console.error(`Unrecognised line in ${IN}: ${JSON.stringify(line)}`);
    process.exit(1);
  }
  if (!current) {
    console.error(`Header before any path rule in ${IN}: ${JSON.stringify(line)}`);
    process.exit(1);
  }
  current.headers.push([m[1], m[2].trim()]);
}

/** nginx `add_header` value — escape the quotes nginx would otherwise eat. */
const quote = (v) => `"${v.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

/** `/pagefind/index/*` -> `^/pagefind/index/`; `/sw.js` -> exact. */
function toLocation(path) {
  if (path === '/*') return null; // global — emitted at server level
  if (path.endsWith('/*')) return { op: '^~', match: path.slice(0, -1) };
  return { op: '=', match: path };
}

const globalRule = rules.find((r) => r.path === '/*');
const pathRules = rules.filter((r) => r.path !== '/*');

// More specific paths must come first: /pagefind/index/ has to beat /pagefind/.
pathRules.sort((a, b) => b.path.length - a.path.length);

const out = [
  '# GENERATED by scripts/headers-to-nginx.mjs from dist/_headers — do not edit.',
  '# Regenerate with: node scripts/headers-to-nginx.mjs',
  '',
];

if (globalRule) {
  out.push('# Applies to every response (the `/*` rule).');
  for (const [k, v] of globalRule.headers) {
    out.push(`add_header ${k} ${quote(v)} always;`);
  }
  out.push('');
}

for (const rule of pathRules) {
  const loc = toLocation(rule.path);
  if (!loc) continue;
  out.push(`location ${loc.op} ${loc.match} {`);
  // add_header in a location block drops inherited ones, so the global set is
  // repeated inside each — this is nginx's documented inheritance rule, not a
  // redundancy that can be trimmed.
  for (const [k, v] of globalRule?.headers ?? []) {
    out.push(`  add_header ${k} ${quote(v)} always;`);
  }
  for (const [k, v] of rule.headers) {
    out.push(`  add_header ${k} ${quote(v)} always;`);
  }
  out.push('}');
  out.push('');
}

writeFileSync(OUT, out.join('\n'));
console.log(
  `headers-to-nginx: wrote ${OUT} — ${globalRule?.headers.length ?? 0} global header(s), ` +
    `${pathRules.length} path rule(s).`,
);
